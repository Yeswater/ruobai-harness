#!/usr/bin/env node
/**
 * Regenerate the production runtime package the desktop ships.
 *
 * The harness loads its plugins by package name from `cordis.yml`, so the
 * packaged app needs every plugin as a *direct* dependency of the deployed
 * root — a transitive copy inside `.pnpm` is not reachable from the config
 * directory. Listing them explicitly keeps `pnpm deploy --prod` exact and the
 * lockfile frozen; this script is the source of truth and `--check` guards
 * against cordis.yml drifting ahead of it.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..')
const target = join(root, 'apps/desktop-runtime/package.json')

// Mounted by the CLI itself rather than by cordis.yml.
const EXTRA = [
  '@ruobai/harness-cli',
  '@ruobai/cordis-plugin-include',
  '@ruobai/cordis-plugin-loader',
  '@ruobai/cordis-plugin-logger-console',
]

function pluginNames() {
  const config = readFileSync(join(root, 'cordis.yml'), 'utf8')
  const names = new Set(EXTRA)
  for (const line of config.split('\n')) {
    const match = line.match(/^\s*name:\s*'([^']+)'/)
    if (match) names.add(match[1])
  }
  return [...names].sort()
}

function dependencies() {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  const deps = Object.fromEntries(pluginNames().map(name => [name, 'workspace:*']))
  deps.tsx = pkg.devDependencies?.tsx ?? '^4.19.0'
  return deps
}

const check = process.argv.includes('--check')
const next = dependencies()
let current
try {
  current = JSON.parse(readFileSync(target, 'utf8')).dependencies ?? {}
} catch {
  current = {}
}

if (check) {
  const names = new Set([...Object.keys(next), ...Object.keys(current)])
  const drift = [...names].filter(name => next[name] !== current[name])
  if (drift.length) {
    console.error(`apps/desktop-runtime/package.json is out of date (${drift.length}):`)
    for (const name of drift) console.error(`  ${name}: ${current[name] ?? '-'} -> ${next[name] ?? '-'}`)
    console.error('Run: node apps/desktop/scripts/sync-runtime.mjs')
    process.exit(1)
  }
  console.log('desktop runtime package is in sync')
  process.exit(0)
}

mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, `${JSON.stringify({
  name: '@ruobai/desktop-runtime',
  version: '0.0.0',
  private: true,
  type: 'module',
  description: 'Generated by apps/desktop/scripts/sync-runtime.mjs; deploy with pnpm deploy --prod.',
  dependencies: next,
}, null, 2)}\n`)
console.log(`wrote ${target} (${Object.keys(next).length} dependencies)`)
